// Front-end for the AI Job Interview Coach.
// Plain JavaScript on purpose: no build step, so the whole demo runs with one
// `uvicorn` command. Every value coming from the API (LLM output, document
// text) is HTML-escaped before rendering to prevent script injection.

const $ = (id) => document.getElementById(id);
const state = { sessionId: null, questionId: null, history: [], skillNames: [] };

// ---------------------------------------------------------------- utilities

function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

// Turn "[S1]" / "[S1, S3]" citations into small badges (after escaping).
function withCitations(text) {
  return escapeHtml(text).replace(/\[(S\d+(?:\s*,\s*S?\d+)*)\]/g, (_, refs) =>
    refs.split(/\s*,\s*/).map((r) => `<span class="cite">${r.startsWith("S") ? r : "S" + r}</span>`).join(""));
}

async function api(path, options = {}) {
  let response;
  try {
    response = await fetch(path, options);
  } catch {
    throw new Error("Cannot reach the server. Is the application running?");
  }
  let body = null;
  try { body = await response.json(); } catch { /* non-JSON error */ }
  if (!response.ok) {
    throw new Error(body?.message || `Request failed (${response.status}).`);
  }
  return body;
}

function postJson(path, payload) {
  return api(path, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(payload) });
}

function show(el, visible = true) { el.hidden = !visible; }

function showError(el, message) {
  el.textContent = message;
  show(el, !!message);
}

function setStep(step) {
  document.querySelectorAll("#stepper li").forEach((li) => {
    const n = Number(li.dataset.step);
    li.classList.toggle("active", n === step);
    li.classList.toggle("done", n < step);
  });
}

function renderList(el, items, emptyText = "None") {
  el.innerHTML = items?.length ? items.map((i) => `<li>${withCitations(i)}</li>`).join("") : `<li class="empty">${emptyText}</li>`;
}

function renderSources(el, sources) {
  el.innerHTML = sources?.length
    ? sources.map((s, i) => `
        <div class="source">
          <div class="source-head"><span><span class="cite">S${i + 1}</span> ${escapeHtml(s.label)}</span><span>similarity ${s.score.toFixed(2)}</span></div>
          <div class="source-text">${escapeHtml(s.text)}</div>
        </div>`).join("")
    : '<p class="empty">No context was retrieved.</p>';
}

function renderWarnings(el, warnings) {
  el.innerHTML = (warnings || []).map((w) => `<div class="alert alert-warn">${escapeHtml(w)}</div>`).join("");
}

const GENERATED_LABEL = {
  llm: "Generated by LLM (RAG)",
  offline: "Offline mode (no LLM)",
  "offline-fallback": "LLM unavailable: offline fallback",
};

function setBadge(el, generatedBy) {
  el.textContent = GENERATED_LABEL[generatedBy] || generatedBy;
  el.className = `badge ${generatedBy}`;
}

function setRing(el, pct) {
  el.style.setProperty("--pct", Math.max(0, Math.min(100, pct)));
  el.style.setProperty("--ring", pct >= 70 ? "var(--good)" : pct >= 45 ? "var(--warn)" : "var(--bad)");
}

function bars(el, rows) {
  el.innerHTML = rows.map((r) => `
    <div class="bar-row ${r.na ? "na" : ""}" title="${escapeHtml(r.title || "")}">
      <div class="label">${escapeHtml(r.label)}${r.sub ? `<small>${escapeHtml(r.sub)}</small>` : ""}</div>
      <div class="bar"><span style="width:${r.na ? 0 : r.pct}%"></span></div>
      <div class="value">${r.na ? "n/a" : escapeHtml(r.value)}</div>
    </div>`).join("");
}

// ---------------------------------------------------------------- step 1: documents

function updateCounts() {
  $("cv-count").textContent = `${$("cv-text").value.length.toLocaleString()} characters`;
  $("job-count").textContent = `${$("job-text").value.length.toLocaleString()} characters`;
}

async function uploadFile(kind, file) {
  if (!file) return;
  const errorEl = $("doc-error");
  showError(errorEl, "");
  $(`${kind}-file-name`).textContent = `Extracting ${file.name}…`;
  const form = new FormData();
  form.append("file", file);
  try {
    const result = await api("/api/documents/extract", { method: "POST", body: form });
    $(`${kind}-text`).value = result.text;
    $(`${kind}-file-name`).textContent = `✓ ${result.filename} (${result.characters.toLocaleString()} characters extracted)`;
    $(`${kind}-text`).dataset.name = result.filename;
  } catch (err) {
    $(`${kind}-file-name`).textContent = "";
    showError(errorEl, `${kind === "cv" ? "CV" : "Job description"}: ${err.message}`);
  }
  updateCounts();
}

function setupDropzone(kind) {
  const input = $(`${kind}-file`);
  const zone = input.closest(".dropzone");
  input.addEventListener("change", () => uploadFile(kind, input.files[0]));
  ["dragenter", "dragover"].forEach((e) => zone.addEventListener(e, (ev) => { ev.preventDefault(); zone.classList.add("drag"); }));
  ["dragleave", "drop"].forEach((e) => zone.addEventListener(e, (ev) => { ev.preventDefault(); zone.classList.remove("drag"); }));
  zone.addEventListener("drop", (ev) => uploadFile(kind, ev.dataTransfer.files[0]));
}

async function loadSamples() {
  try {
    const s = await api("/api/documents/samples");
    $("cv-text").value = s.cv_text;
    $("cv-text").dataset.name = s.cv_name;
    $("job-text").value = s.job_text;
    $("job-text").dataset.name = s.job_name;
    $("cv-file-name").textContent = `✓ ${s.cv_name} (fictional sample)`;
    $("job-file-name").textContent = `✓ ${s.job_name} (fictional sample)`;
    updateCounts();
  } catch (err) {
    showError($("doc-error"), err.message);
  }
}

// The analysis is a single request; these messages narrate the pipeline
// stages while it runs so the audience sees what is happening.
const STAGES = [
  "Cleaning and validating documents…",
  "Splitting into section-aware chunks (tokenizer)…",
  "Embedding chunks with all-MiniLM-L6-v2…",
  "Building the FAISS index…",
  "Scoring skills and requirements…",
  "Retrieving context and generating insights…",
];

async function analyze() {
  const cv = $("cv-text").value.trim();
  const job = $("job-text").value.trim();
  const errorEl = $("doc-error");
  if (!cv || !job) {
    showError(errorEl, !cv ? "Please provide your CV (upload a file or paste the text)." : "Please provide the job description.");
    return;
  }
  showError(errorEl, "");
  const btn = $("analyze-btn");
  btn.disabled = true;
  show($("analyze-loading"));
  let stage = 0;
  $("analyze-stage").textContent = STAGES[0];
  const timer = setInterval(() => {
    stage = Math.min(stage + 1, STAGES.length - 1);
    $("analyze-stage").textContent = STAGES[stage];
  }, 900);
  try {
    const result = await postJson("/api/analyze", {
      cv_text: cv, job_text: job,
      cv_name: $("cv-text").dataset.name || "cv", job_name: $("job-text").dataset.name || "job_description",
    });
    state.sessionId = result.session_id;
    state.history = [];
    renderAnalysis(result);
    show($("step-analysis"));
    show($("step-interview"), false);
    setStep(2);
    $("step-analysis").scrollIntoView({ behavior: "smooth" });
  } catch (err) {
    showError(errorEl, err.message);
  } finally {
    clearInterval(timer);
    btn.disabled = false;
    show($("analyze-loading"), false);
  }
}

// ---------------------------------------------------------------- step 2: analysis

function renderAnalysis(r) {
  const m = r.match;
  $("overall-score").textContent = Math.round(m.overall_score);
  setRing($("score-ring"), m.overall_score);
  bars($("breakdown"), m.breakdown.map((b) => ({
    label: b.label, sub: b.applicable ? `weight ${Math.round(b.weight * 100)}%` : "not applicable",
    pct: b.score, value: `${Math.round(b.score)}%`, na: !b.applicable, title: b.explanation,
  })));
  $("disclaimer").textContent = m.disclaimer + " Hover a bar to see how it was computed.";

  $("matching-skills").innerHTML = m.matching_skills.length
    ? m.matching_skills.map((s) => `<span class="chip chip-match ${s.implied ? "implied" : ""}" title="${s.implied ? "Implied by a more specific skill in the CV" : s.importance}">${escapeHtml(s.name)}</span>`).join("")
    : '<span class="empty">No job skill found in the CV.</span>';
  $("missing-skills").innerHTML = m.missing_skills.length
    ? m.missing_skills.map((s) => `<span class="chip ${s.importance === "required" ? "chip-missing" : "chip-preferred"}" title="${s.importance}">${escapeHtml(s.name)}</span>`).join("")
    : '<span class="empty">No missing skill detected.</span>';

  setBadge($("insights-badge"), r.insights_generated_by);
  renderWarnings($("analysis-warnings"), r.warnings);
  $("insights-summary").innerHTML = withCitations(r.insights.summary);
  renderList($("insights-strengths"), r.insights.strengths);
  renderList($("insights-gaps"), r.insights.gaps, "No significant gap found");
  renderList($("insights-recs"), r.insights.recommendations);
  renderSources($("insights-sources"), r.insights_sources);

  $("req-count").textContent = `(${m.requirements.filter((x) => x.status === "covered").length}/${m.requirements.length} covered)`;
  $("requirements").innerHTML = m.requirements.map((q) => `
    <tr>
      <td>${escapeHtml(q.text)}${q.kind === "preferred" ? ' <span class="muted small">(nice to have)</span>' : ""}</td>
      <td><span class="status ${q.status}">${q.status}</span> <span class="muted small">${Math.round(q.coverage)}%</span></td>
      <td class="evidence">${q.evidence ? `<strong>${escapeHtml(q.evidence.label)}</strong> · sim ${q.evidence.score.toFixed(2)}<br>${escapeHtml(q.evidence.text.slice(0, 220))}${q.evidence.text.length > 220 ? "…" : ""}` : "No convincing evidence found in the CV"}</td>
    </tr>`).join("");

  const p = r.pipeline;
  const docs = Object.fromEntries(r.documents.map((d) => [d.doc_type, d]));
  $("pipeline-info").innerHTML = [
    ["CV", `${docs.cv.characters.toLocaleString()} chars → ${docs.cv.chunks} chunks (${docs.cv.total_tokens} tokens)`],
    ["Job description", `${docs.job.characters.toLocaleString()} chars → ${docs.job.chunks} chunks (${docs.job.total_tokens} tokens)`],
    ["Tokenizer", p.tokenizer],
    ["Embedding model", `${p.embedding_model} (${p.embedding_dimension} dimensions)`],
    ["Vector index", `${p.index_type}, ${p.index_size} vectors`],
    ["LLM", p.llm],
  ].map(([k, v]) => `<div><strong>${escapeHtml(k)}</strong>${escapeHtml(v)}</div>`).join("");
}

// ---------------------------------------------------------------- step 3: interview

async function nextQuestion() {
  if (!state.sessionId) return;
  const errorEl = $("interview-error");
  showError(errorEl, "");
  show($("feedback"), false);
  show($("question-card"), false);
  show($("question-loading"));
  $("next-question").disabled = true;
  try {
    const category = $("category").value || null;
    const q = await postJson("/api/interview/question", { session_id: state.sessionId, category });
    state.questionId = q.question_id;
    renderQuestion(q);
  } catch (err) {
    showError(errorEl, err.message);
  } finally {
    show($("question-loading"), false);
    $("next-question").disabled = false;
  }
}

function renderQuestion(q) {
  const item = q.question;
  $("q-meta").innerHTML = `
    <span class="badge">Question ${q.question_number}</span>
    <span class="badge">${escapeHtml(item.category)}</span>
    <span class="badge">${escapeHtml(item.difficulty)}</span>
    <span class="badge">Focus: ${escapeHtml(item.focus)}</span>
    <span class="badge ${q.generated_by}">${escapeHtml(GENERATED_LABEL[q.generated_by])}</span>`;
  $("q-text").innerHTML = withCitations(item.question);
  $("q-rationale").innerHTML = withCitations(item.rationale);
  renderSources($("q-sources"), q.sources);
  if (q.warnings?.length) showError($("interview-error"), q.warnings.join(" "));
  $("answer").value = "";
  show($("question-card"));
  $("answer").focus();
}

async function submitAnswer() {
  const answer = $("answer").value.trim();
  const errorEl = $("interview-error");
  if (!answer) {
    showError(errorEl, "Please write an answer before submitting.");
    return;
  }
  showError(errorEl, "");
  const btn = $("submit-answer");
  btn.disabled = true;
  show($("answer-loading"));
  try {
    const e = await postJson("/api/interview/answer", { session_id: state.sessionId, question_id: state.questionId, answer });
    renderFeedback(e);
  } catch (err) {
    showError(errorEl, err.message);
  } finally {
    btn.disabled = false;
    show($("answer-loading"), false);
  }
}

function renderFeedback(e) {
  const ev = e.evaluation;
  $("answer-score").textContent = e.score.toFixed(1);
  setRing($("answer-ring"), e.score * 10);
  setBadge($("feedback-badge"), e.generated_by);
  renderWarnings($("feedback-warnings"), e.warnings);
  const labels = { relevance: "Relevance", specificity: "Specificity", structure: "Structure", job_alignment: "Job alignment" };
  bars($("criteria"), Object.entries(ev.criteria).map(([k, v]) => ({ label: labels[k] || k, pct: v * 10, value: `${v}/10` })));
  renderList($("fb-strengths"), ev.strengths);
  renderList($("fb-weaknesses"), ev.weaknesses);
  renderList($("fb-missing"), ev.missing_points);
  renderList($("fb-suggestions"), ev.improvement_suggestions);
  $("fb-improved").innerHTML = withCitations(ev.improved_answer);
  $("fb-grounding").innerHTML = ev.grounding_note ? `Grounding: ${withCitations(ev.grounding_note)}` : "";
  renderSources($("fb-sources"), e.sources);
  show($("feedback"));

  state.history.push({ question: $("q-text").textContent, score: e.score });
  $("history").innerHTML = state.history.map((h) => `<li><strong>${h.score.toFixed(1)}/10</strong> · ${escapeHtml(h.question.slice(0, 140))}${h.question.length > 140 ? "…" : ""}</li>`).join("");
  show($("history-wrap"));
  $("feedback").scrollIntoView({ behavior: "smooth" });
}

// ---------------------------------------------------------------- init

async function checkHealth() {
  const pill = $("mode-pill");
  try {
    const h = await api("/api/health");
    if (h.llm_configured) {
      pill.textContent = `LLM: ${h.llm_model}`;
      pill.className = "pill pill-llm";
    } else {
      pill.textContent = "Offline mode (no LLM key)";
      pill.className = "pill pill-offline";
      pill.title = "Set LLM_API_KEY in .env to enable LLM generation. Retrieval and scoring still work.";
    }
  } catch {
    pill.textContent = "Server unreachable";
  }
}

document.addEventListener("DOMContentLoaded", () => {
  setupDropzone("cv");
  setupDropzone("job");
  $("cv-text").addEventListener("input", updateCounts);
  $("job-text").addEventListener("input", updateCounts);
  $("load-sample").addEventListener("click", loadSamples);
  $("analyze-btn").addEventListener("click", analyze);
  $("start-interview").addEventListener("click", () => {
    show($("step-interview"));
    setStep(3);
    $("step-interview").scrollIntoView({ behavior: "smooth" });
    nextQuestion();
  });
  $("next-question").addEventListener("click", nextQuestion);
  $("continue-btn").addEventListener("click", nextQuestion);
  $("submit-answer").addEventListener("click", submitAnswer);
  checkHealth();
  updateCounts();
});
